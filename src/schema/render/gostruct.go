// Go struct styles.
const (
	// GoStyleGORM tags fields for GORM (column, primaryKey, indexes, not null, default) and adds TableName().
	GoStyleGORM = "gorm"
	// GoStylePlain tags fields with `db:"column"` (sqlx, scany, ...) and `json:"field"`.
	GoStylePlain = "plain"
)

// GoOptions configure Go.
type GoOptions struct {
	// Package is the package clause of the file (default "models").
	Package string
	// Style is GoStyleGORM (default) or GoStylePlain.
	Style string
	// Dialect, when set, adds GORM `type:` tags with the exact column types of render.SQL for that dialect,
	// so that GORM's AutoMigrate creates the same columns. Without it GORM picks its own types.
	Dialect Dialect
}

// Go returns one gofmt'd Go file with a struct per registry model, for apps that query goauth's tables
// themselves. Struct names are the exported Go names of the logical models (User, Session, Account,
// Verification, RateLimit, plugin models), field names the exported Go names of the logical fields
// (UserID, EmailVerified) and every field carries `json:"<logical name>"`.
//
// Types: string, float64 (number), int64 (integer, and ids under the serial strategy), bool, time.Time,
// json.RawMessage (json), []string and []float64; fields that are not required are pointers (slices and
// json.RawMessage stay nil-able values). The GORM style tags columns, the primary key (autoIncrement for
// serial ids, default:(-) for database ids), not null, constant defaults, autoCreateTime/autoUpdateTime,
// the indexes of render.SQL (same names; priority for multi-column ones) and serializer:json for arrays,
// and adds a TableName method. GORM sees no associations, so AutoMigrate creates no foreign keys: use
// goauth's migrator (or render.SQL) to create the tables.
func Go(reg *schema.Registry, opts GoOptions) (string, error) {
	// Step 1: options
	pkg := opts.Package
	if pkg == "" {
		pkg = "models"
	}
	if !token.IsIdentifier(pkg) {
		return "", fmt.Errorf("render: go: invalid package name %q", pkg)
	}
	style := opts.Style
	if style == "" {
		style = GoStyleGORM
	}
	if style != GoStyleGORM && style != GoStylePlain {
		return "", fmt.Errorf("render: go: unknown style %q (use %s or %s)", style, GoStyleGORM, GoStylePlain)
	}
	if opts.Dialect != "" {
		if err := opts.Dialect.valid(); err != nil {
			return "", err
		}
	}
	// Step 2: the structs
	var body strings.Builder
	imports := map[string]bool{}
	seen := map[string]string{}
	for _, m := range reg.Models() {
		name := GoName(m.Name())
		if other, dup := seen[name]; dup {
			return "", fmt.Errorf("render: go: models %q and %q both become type %s", other, m.Name(), name)
		}
		seen[name] = m.Name()
		if err := writeGoStruct(&body, reg, m, name, style, opts.Dialect, imports); err != nil {
			return "", err
		}
	}
	// Step 3: header, package clause and imports
	var b strings.Builder
	b.WriteString("// Code generated by goauth schema --format go; DO NOT EDIT.\n\n")
	b.WriteString("// Package " + pkg + " holds goauth's tables as Go structs (" + style + " style), generated from goauth's\n" +
		"// schema registry (core models, additionalFields and plugin schemas).\n")
	b.WriteString("package " + pkg + "\n\n")
	if len(imports) > 0 {
		b.WriteString("import (\n")
		for _, imp := range []string{"encoding/json", "time"} {
			if imports[imp] {
				b.WriteString("\t" + strconv.Quote(imp) + "\n")
			}
		}
		b.WriteString(")\n\n")
	}
	b.WriteString(body.String())
	// Step 4: gofmt
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("render: go: format: %w", err)
	}
	return string(src), nil
}

// writeGoStruct renders one struct (and its TableName method in the GORM style).
func writeGoStruct(b *strings.Builder, reg *schema.Registry, m *schema.ResolvedModel, name, style string, d Dialect, imports map[string]bool) error {
	fmt.Fprintf(b, "// %s is goauth's %q model (table %q).\n", name, m.Name(), m.Table())
	fmt.Fprintf(b, "type %s struct {\n", name)
	// Step 1: index tags per field, from the same specs as render.SQL
	indexTags := map[string][]string{}
	for _, idx := range m.IndexSpecs() {
		kind := "index"
		if idx.Unique {
			kind = "uniqueIndex"
		}
		for i, fn := range idx.Fields {
			tag := kind + ":" + idx.Name
			if len(idx.Fields) > 1 {
				tag += ",priority:" + strconv.Itoa(i+1)
			}
			indexTags[fn] = append(indexTags[fn], tag)
		}
	}
	// Step 2: one field per registry field
	seen := map[string]string{}
	for _, f := range m.Fields() {
		fieldName := GoName(f.Name)
		if other, dup := seen[fieldName]; dup {
			return fmt.Errorf("render: go: %s: fields %q and %q both become %s", m.Name(), other, f.Name, fieldName)
		}
		seen[fieldName] = f.Name
		typ := goType(reg, f, imports)
		var tags []string
		if style == GoStyleGORM {
			tags = append(tags, fmt.Sprintf("gorm:%q", gormTag(reg, f, d, indexTags[f.Name])))
		} else {
			tags = append(tags, fmt.Sprintf("db:%q", f.Column))
		}
		tags = append(tags, fmt.Sprintf("json:%q", f.Name))
		// a trailing comment keeps gofmt's alignment of the whole struct
		comment := ""
		if f.References != nil {
			target, _ := reg.Model(f.References.Model)
			comment = fmt.Sprintf(" // references %s.%s", GoName(target.Name()), GoName(f.References.Field))
		}
		fmt.Fprintf(b, "\t%s %s `%s`%s\n", fieldName, typ, strings.Join(tags, " "), comment)
	}
	b.WriteString("}\n\n")
	// Step 3: GORM's table name
	if style == GoStyleGORM {
		fmt.Fprintf(b, "// TableName returns the table of %s.\n", name)
		fmt.Fprintf(b, "func (%s) TableName() string { return %q }\n\n", name, m.Table())
	}
	return nil
}

// goType returns the Go type of a field (a pointer when it is optional), recording the imports it needs.
func goType(reg *schema.Registry, f schema.ResolvedField, imports map[string]bool) string {
	var typ string
	// Step 1: ids follow the id strategy
	switch {
	case f.HoldsID():
		typ = "string"
		if reg.IDStrategy() == schema.IDSerial {
			typ = "int64"
		}
	case f.Type == schema.Number:
		typ = "float64"
	case f.Type == schema.Integer:
		typ = "int64"
	case f.Type == schema.Boolean:
		typ = "bool"
	case f.Type == schema.Date:
		typ = "time.Time"
		imports["time"] = true
	case f.Type == schema.JSON:
		// Step 2: nil-able types are never pointers
		imports["encoding/json"] = true
		return "json.RawMessage"
	case f.Type == schema.StringArray:
		return "[]string"
	case f.Type == schema.NumberArray:
		return "[]float64"
	default:
		typ = "string"
	}
	if !f.Required && f.Type != schema.ID {
		return "*" + typ
	}
	return typ
}

// gormTag renders the gorm struct tag of a field.
func gormTag(reg *schema.Registry, f schema.ResolvedField, d Dialect, indexes []string) string {
	parts := []string{"column:" + f.Column}
	// Step 1: the primary key
	if f.Type == schema.ID {
		parts = append(parts, "primaryKey")
		switch reg.IDStrategy() {
		case schema.IDSerial:
			parts = append(parts, "autoIncrement")
		case schema.IDDatabase:
			// GORM omits the zero id on insert and reads the database's default back
			parts = append(parts, "default:(-)")
		}
		if d != "" {
			// the type alone ("text", "varchar(36)", "bigint"); GORM adds the key and identity itself
			parts = append(parts, "type:"+strings.Fields(idColumn(reg.IDStrategy(), d))[0])
		} else if reg.IDStrategy() != schema.IDSerial {
			parts = append(parts, "size:255")
		}
		return strings.Join(parts, ";")
	}
	// Step 2: the column type: exact with a dialect, otherwise a bounded string where MySQL needs one
	switch {
	case d != "":
		parts = append(parts, "type:"+ColumnType(reg, f, d))
	case f.Type == schema.String && !(f.HoldsID() && reg.IDStrategy() == schema.IDSerial) && ColumnType(reg, f, MySQL) != "text":
		parts = append(parts, "size:255")
	}
	if f.Type == schema.StringArray || f.Type == schema.NumberArray {
		parts = append(parts, "serializer:json")
	}
	// Step 3: NOT NULL, defaults and GORM's timestamps
	if f.Required {
		parts = append(parts, "not null")
	}
	switch {
	case f.Type == schema.Date && f.OnUpdate != nil:
		parts = append(parts, "autoUpdateTime")
	case nowDefault(f):
		parts = append(parts, "autoCreateTime")
	default:
		if def := gormDefault(f); def != "" {
			parts = append(parts, "default:"+def)
		}
	}
	// Step 4: indexes
	parts = append(parts, indexes...)
	return strings.Join(parts, ";")
}

// gormDefault renders a constant default for a gorm tag ('text' for strings).
func gormDefault(f schema.ResolvedField) string {
	if !staticDefault(f) {
		return ""
	}
	v, err := schema.Normalize(f.Type, f.Default)
	if err != nil || v == nil {
		return ""
	}
	switch x := v.(type) {
	case bool:
		return strconv.FormatBool(x)
	case string:
		if strings.ContainsAny(x, `;:"`+"`") {
			return ""
		}
		return "'" + strings.ReplaceAll(x, "'", "''") + "'"
	case float64:
		return strconv.FormatFloat(x, 'g', -1, 64)
	case int64:
		return strconv.FormatInt(x, 10)
	}
	return ""
}

// goInitialisms are upper-cased as a whole in Go names (golint's list, the common subset).
var goInitialisms = map[string]bool{
	"ACL": true, "API": true, "ASCII": true, "CPU": true, "CSS": true, "DNS": true, "EOF": true, "GUID": true,
	"HTML": true, "HTTP": true, "HTTPS": true, "ID": true, "IP": true, "JSON": true, "JWT": true, "LHS": true,
	"OTP": true, "QPS": true, "RAM": true, "RHS": true, "RPC": true, "SLA": true, "SMTP": true, "SQL": true,
	"SSH": true, "SSO": true, "TCP": true, "TLS": true, "TTL": true, "UDP": true, "UI": true, "UID": true,
	"URI": true, "URL": true, "UTF8": true, "UUID": true, "VM": true, "XML": true, "XSRF": true, "XSS": true,
}

// GoName returns the exported Go name of a logical model or field name: "user" → "User", "userId" →
// "UserID", "lastLoginIP" → "LastLoginIP", "rate_limit" → "RateLimit", "callbackUrl" → "CallbackURL".
func GoName(name string) string {
	var b strings.Builder
	// Step 1: split on separators and case changes, then upper-case each word (initialisms entirely)
	for _, w := range splitWords(name) {
		if up := strings.ToUpper(w); goInitialisms[up] {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	out := b.String()
	// Step 2: a Go identifier can't start with a digit
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "X" + out
	}
	return out
}

// splitWords splits "lastLoginIP" into last, Login, IP and "rate_limit" into rate, limit.
func splitWords(name string) []string {
	var words []string
	var cur []rune
	rs := []rune(name)
	flush := func() {
		if len(cur) > 0 {
			words = append(words, string(cur))
			cur = nil
		}
	}
	for i, r := range rs {
		switch {
		case !unicode.IsLetter(r) && !unicode.IsDigit(r):
			flush()
			continue
		case unicode.IsUpper(r) && len(cur) > 0:
			prevLower := unicode.IsLower(cur[len(cur)-1]) || unicode.IsDigit(cur[len(cur)-1])
			nextLower := i+1 < len(rs) && unicode.IsLower(rs[i+1])
			// a new word starts at "aB" and at the last capital of "ABc" (IPAddress → IP, Address)
			if prevLower || nextLower {
				flush()
			}
		}
		cur = append(cur, r)
	}
	flush()
	return words
}
