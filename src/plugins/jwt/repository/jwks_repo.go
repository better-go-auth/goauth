package repository

import (
	"context"
	"errors"
	"fmt"

	"github.com/better-go-auth/goauth/src/adapter"
	"github.com/better-go-auth/goauth/src/adapter/recordbind"
	jwtmodels "github.com/better-go-auth/goauth/src/plugins/jwt/models"
	"github.com/better-go-auth/goauth/src/schema"
)

// IJwksRepo defines the repository interface for storing and retrieving JWKS keys.
type IJwksRepo interface {
	// GetAllKeys returns every key, newest first.
	GetAllKeys(ctx context.Context) ([]jwtmodels.JWK, error)
	// GetLatestKey returns the newest key, or (nil, nil).
	GetLatestKey(ctx context.Context) (*jwtmodels.JWK, error)
	// CreateJWK stores jwk and fills in its ID (generated by the adapter or the database when empty).
	CreateJWK(ctx context.Context, jwk *jwtmodels.JWK) error
}

// adapterJwksRepo stores keys through the storage adapter (any backend).
type adapterJwksRepo struct {
	store adapter.Adapter
	b     *recordbind.Binding[jwtmodels.JWK]
}

// New returns the jwks repository on store. reg must declare the jwks model (jwtmodels.Schema).
func New(store adapter.Adapter, reg *schema.Registry) (IJwksRepo, error) {
	if store == nil || reg == nil {
		return nil, errors.New("jwt: a storage adapter and the schema registry are required")
	}
	b, err := recordbind.New[jwtmodels.JWK](reg, jwtmodels.ModelJWKS,
		recordbind.Field{Go: "ID", Name: "id"},
		recordbind.Field{Go: "PublicKey", Name: "publicKey"},
		recordbind.Field{Go: "PrivateKey", Name: "privateKey"},
		recordbind.Field{Go: "CreatedAt", Name: "createdAt"},
		recordbind.Field{Go: "ExpiresAt", Name: "expiresAt"},
		recordbind.Field{Go: "Alg", Name: "alg"},
		recordbind.Field{Go: "Crv", Name: "crv"},
	)
	if err != nil {
		return nil, err
	}
	return &adapterJwksRepo{store: store, b: b}, nil
}

// newestFirst sorts keys by creation time (id breaks ties so the order is stable).
var newestFirst = []adapter.SortBy{{Field: "createdAt", Desc: true}, {Field: "id", Desc: true}}

func (r *adapterJwksRepo) GetAllKeys(ctx context.Context) ([]jwtmodels.JWK, error) {
	recs, err := r.store.FindMany(ctx, r.b.Model(), adapter.Query{Sort: newestFirst})
	if err != nil {
		return nil, fmt.Errorf("jwt: list keys: %w", err)
	}
	return r.b.DecodeAll(recs)
}

func (r *adapterJwksRepo) GetLatestKey(ctx context.Context) (*jwtmodels.JWK, error) {
	recs, err := r.store.FindMany(ctx, r.b.Model(), adapter.Query{Sort: newestFirst, Limit: 1})
	if err != nil {
		return nil, fmt.Errorf("jwt: latest key: %w", err)
	}
	if len(recs) == 0 {
		return nil, nil
	}
	return r.b.Decode(recs[0])
}

func (r *adapterJwksRepo) CreateJWK(ctx context.Context, jwk *jwtmodels.JWK) error {
	// Step 1: insert
	rec, err := r.store.Create(ctx, r.b.Model(), r.b.Record(jwk))
	if err != nil {
		return fmt.Errorf("jwt: create key: %w", err)
	}
	// Step 2: hand the stored row (generated id) back to the caller
	stored, err := r.b.Decode(rec)
	if err != nil {
		return err
	}
	*jwk = *stored
	return nil
}
