// Package repository persists the two-factor plugin's rows.
package repository

import (
	"context"
	"errors"
	"fmt"

	"github.com/better-go-auth/goauth/src/adapter"
	"github.com/better-go-auth/goauth/src/adapter/recordbind"
	tfmodels "github.com/better-go-auth/goauth/src/plugins/two-factor/models"
	"github.com/better-go-auth/goauth/src/schema"
)

// ITwoFactorRepo stores the twoFactor rows.
type ITwoFactorRepo interface {
	// FindByUserID returns the user's row, or (nil, nil).
	FindByUserID(ctx context.Context, userID string) (*tfmodels.TwoFactor, error)
	// Create inserts row and fills in its ID (generated by the adapter or the database when empty).
	Create(ctx context.Context, row *tfmodels.TwoFactor) error
	// DeleteByUserID deletes every row of the user.
	DeleteByUserID(ctx context.Context, userID string) error
	// SetVerified marks the row verified.
	SetVerified(ctx context.Context, id string) error
	// UpdateBackupCodes replaces the stored backup codes.
	UpdateBackupCodes(ctx context.Context, id, backupCodes string) error
	// SwapBackupCodes replaces the stored backup codes only when they still equal old (compare-and-swap
	// so one backup code cannot be used twice concurrently). It reports whether a row was updated.
	SwapBackupCodes(ctx context.Context, id, old, updated string) (bool, error)
}

// adapterRepo stores twoFactor rows through the storage adapter (any backend; joins the transaction in ctx).
type adapterRepo struct {
	store adapter.Adapter
	b     *recordbind.Binding[tfmodels.TwoFactor]
}

// New returns the repository on store. reg must declare the twoFactor model (tfmodels.Schema).
func New(store adapter.Adapter, reg *schema.Registry) (ITwoFactorRepo, error) {
	if store == nil || reg == nil {
		return nil, errors.New("two-factor: a storage adapter and the schema registry are required")
	}
	b, err := recordbind.New[tfmodels.TwoFactor](reg, tfmodels.ModelTwoFactor,
		recordbind.Field{Go: "ID", Name: "id"},
		recordbind.Field{Go: "Secret", Name: "secret"},
		recordbind.Field{Go: "BackupCodes", Name: "backupCodes"},
		recordbind.Field{Go: "UserID", Name: "userId"},
		recordbind.Field{Go: "Verified", Name: "verified"},
	)
	if err != nil {
		return nil, err
	}
	return &adapterRepo{store: store, b: b}, nil
}

func eq(field string, v any) []adapter.Where { return []adapter.Where{{Field: field, Value: v}} }

func (r *adapterRepo) FindByUserID(ctx context.Context, userID string) (*tfmodels.TwoFactor, error) {
	rec, err := r.store.FindOne(ctx, r.b.Model(), eq("userId", userID))
	if errors.Is(err, adapter.ErrNotFound) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("two-factor: find: %w", err)
	}
	return r.b.Decode(rec)
}

func (r *adapterRepo) Create(ctx context.Context, row *tfmodels.TwoFactor) error {
	// Step 1: insert (verified=false is written, not left to the column default)
	rec, err := r.store.Create(ctx, r.b.Model(), r.b.Record(row))
	if err != nil {
		return fmt.Errorf("two-factor: create: %w", err)
	}
	// Step 2: hand the stored row (generated id) back to the caller
	stored, err := r.b.Decode(rec)
	if err != nil {
		return err
	}
	*row = *stored
	return nil
}

func (r *adapterRepo) DeleteByUserID(ctx context.Context, userID string) error {
	_, err := r.store.DeleteMany(ctx, r.b.Model(), eq("userId", userID))
	return err
}

func (r *adapterRepo) SetVerified(ctx context.Context, id string) error {
	_, err := r.store.UpdateMany(ctx, r.b.Model(), eq("id", id), adapter.Record{"verified": true})
	return err
}

func (r *adapterRepo) UpdateBackupCodes(ctx context.Context, id, backupCodes string) error {
	_, err := r.store.UpdateMany(ctx, r.b.Model(), eq("id", id), adapter.Record{"backupCodes": backupCodes})
	return err
}

func (r *adapterRepo) SwapBackupCodes(ctx context.Context, id, old, updated string) (bool, error) {
	where := []adapter.Where{{Field: "id", Value: id}, {Field: "backupCodes", Value: old}}
	n, err := r.store.UpdateMany(ctx, r.b.Model(), where, adapter.Record{"backupCodes": updated})
	if err != nil {
		return false, err
	}
	return n > 0, nil
}
